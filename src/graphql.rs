/// The schema's enums and the input objects the resolvers read, generated by `build.rs`.
#[allow(dead_code, reason = "generated for every enum of the schema")]
#[allow(clippy::all, missing_docs)]
pub(crate) mod types {
    include!(concat!(env!("OUT_DIR"), "/graphql_types.rs"));
}

/// GitHub's public GraphQL schema, pinned by `cargo references update`.
const SDL: &str = include_str!("../spec/schema.docs.graphql");

/// A JSON object: a parent value or a field's arguments.
type Map = serde_json::Map<String, Json>;

/// A resolver's typed object, serialized for the dynamic schema.
struct Output(Json);

impl Output {
    /// Serializes `value`; `None` is null.
    fn of(value: impl serde::Serialize) -> Result<Self, Error> {
        serde_json::to_value(value)
            .map(Self)
            .map_err(|error| Error::new(format!("cannot serialize the result: {error}")))
    }
}

/// Computes one field from the environment, the parent object and the field's arguments.
type Resolver = fn(&Env, &Map, &Map) -> Result<Output, Error>;

/// The implemented fields, keyed by `Type.field`.
fn resolvers() -> Vec<(&'static str, Resolver)> {
    let mut fields = Vec::new();
    fields.extend_from_slice(query::RESOLVERS);
    fields.extend_from_slice(pulls::RESOLVERS);
    fields.extend_from_slice(pull_mutations::RESOLVERS);
    fields.extend_from_slice(search::RESOLVERS);
    fields.extend_from_slice(projects::RESOLVERS);
    fields.extend_from_slice(issues::RESOLVERS);
    fields.extend_from_slice(issue_mutations::RESOLVERS);
    fields.extend_from_slice(issue_comments::RESOLVERS);
    fields.extend_from_slice(issue_actions::RESOLVERS);
    fields.extend_from_slice(issue_labels::RESOLVERS);
    fields
}

/// What resolvers can see: the state, the authenticated caller and the base URL.
struct Env {
    state: Arc<Mutex<State>>,
    caller: Caller,
    web_url: String,
}

impl Env {
    /// Locations under the server's base URL, which GraphQL objects link to.
    fn urls(&self) -> crate::urls::Urls<'_> {
        crate::urls::Urls::new(&self.web_url, &self.web_url)
    }

    /// A request carrying this environment's URLs and caller, for REST rendering and webhooks.
    fn request(&self) -> crate::api::ApiRequest {
        crate::api::ApiRequest::for_urls(&self.web_url, Some(self.caller.clone()))
    }
}

/// GitHub's error for a missing object, with its `NOT_FOUND` type.
fn not_found(message: String) -> Error {
    typed_error(message, "NOT_FOUND")
}

/// An error that GitHub reports with a top-level `type`.
fn typed_error(message: impl Into<String>, kind: &'static str) -> Error {
    Error::new(message).extend_with(|_, extensions| extensions.set("type", kind))
}

/// Reads a field's arguments, or its parent object, as `T`.
fn read<T: DeserializeOwned>(object: &Map) -> Result<T, Error> {
    T::deserialize(Json::Object(object.clone()))
        .map_err(|error| Error::new(format!("unexpected arguments or parent: {error}")))
}

/// The arguments of a mutation: its input object.
#[derive(Deserialize)]
struct MutationArgs<T> {
    input: T,
}

/// Arguments naming an account.
#[derive(Deserialize)]
struct LoginArgs {
    login: String,
}

/// Arguments naming a repository of an owner.
#[derive(Deserialize)]
struct NameArgs {
    name: String,
}

/// Arguments naming a repository.
#[derive(Deserialize)]
struct RepositoryArgs {
    owner: String,
    name: String,
}

/// Arguments naming a node.
#[derive(Deserialize)]
struct IdArgs {
    id: String,
}

/// Arguments naming a pull request or issue of a repository.
#[derive(Deserialize)]
struct NumberArgs {
    number: i64,
}

/// The arguments of `User.repositories` and `Organization.repositories` that are applied.
#[derive(Deserialize)]
#[serde(rename_all = "camelCase")]
struct RepositoriesArgs {
    privacy: Option<types::RepositoryPrivacy>,
    is_fork: Option<bool>,
    order_by: Option<types::RepositoryOrder>,
    after: Option<String>,
    first: Option<i64>,
}

/// The arguments of `Query.search` that are applied.
#[derive(Deserialize)]
struct SearchArgs {
    query: String,
    first: Option<i64>,
    last: Option<i64>,
    after: Option<String>,
}

/// The `login` of a parent `User` or `Organization`.
#[derive(Deserialize)]
struct AccountKey {
    login: String,
}

/// The owner and name of a parent `Repository`.
#[derive(Deserialize)]
struct RepositoryKey {
    owner: AccountKey,
    name: String,
}

/// Connection pagination arguments used by list fields.
#[derive(Deserialize)]
struct PageArgs {
    first: Option<i64>,
    last: Option<i64>,
    after: Option<String>,
}

/// The numeric id inside a node id produced by [`node_id`].
pub(crate) fn database_id(node: &str) -> Option<u64> {
    let decoded = String::from_utf8(STANDARD.decode(node).ok()?).ok()?;
    grammar::node_payload.parse(decoded.as_str()).ok()
}

pub use schema::{execute, fields};

/// Decodes a `cursor:<offset>` pagination cursor.
fn cursor_index(cursor: &str) -> Option<usize> {
    STANDARD
        .decode(cursor)
        .ok()
        .and_then(|bytes| String::from_utf8(bytes).ok())
        .and_then(|text| grammar::cursor.parse(text.as_str()).ok())
}

/// Encodes a pagination cursor for `index`.
fn cursor_of(index: usize) -> String {
    STANDARD.encode(format!("cursor:{index}"))
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::render::node_id;

    #[test]
    fn node_ids_round_trip() {
        assert_eq!(database_id(&node_id("User", 42)), Some(42));
        assert_eq!(database_id("MDQ6VXNlcjE="), Some(1));
        assert_eq!(database_id("garbage"), None);
    }

    #[test]
    fn node_ids_round_trip_for_kinds_ending_in_a_digit() {
        assert_eq!(database_id(&node_id("ProjectV2", 4)), Some(4));
        assert_eq!(database_id(&node_id("ProjectV2Item", 17)), Some(17));
    }
}
