//! GitHub's GraphQL API, served from GitHub's published schema in `spec/schema.docs.graphql`.
//!
//! Every type, field, argument, enum and input of the schema exists. A field listed in
//! [`resolvers`] is computed by its resolver, which returns a typed object from [`objects`]
//! that is serialized where it enters the dynamic schema. Any other field reads the same-named
//! field of its parent object, and fails with "Not implemented by ninot-github: Type.field"
//! when the parent's type has no such field. The schema's enums and the input objects the
//! resolvers read are generated from the schema by `build.rs` into [`types`].
//!
//! Gaps against GitHub, from async-graphql's dynamic schema:
//! - It cannot import SDL, so [`schema::build_schema`] converts the parsed document. Applied
//!   directives other than `@deprecated` (`@preview`, `@possibleTypes`, `@docsCategory`) are
//!   dropped, as are directive definitions.
//! - It rejects a field narrower than its interface's, so such a field takes the interface's
//!   type: `User.email` is `String`, not `String!`.
//! - Custom scalars such as `DateTime` and `URI` accept and emit any value.
//! - A failed non-null field is left out of its object instead of nulling the object.

