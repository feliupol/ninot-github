/// A JSON object: a parent value or a field's arguments.
type Map = serde_json::Map<String, Json>;

/// A resolver's typed object, serialized for the dynamic schema.
struct Output(Json);

impl Output {
    /// Serializes `value`; `None` is null.
    fn of(value: impl serde::Serialize) -> Result<Self, Error> {
        serde_json::to_value(value)
            .map(Self)
            .map_err(|error| Error::new(format!("cannot serialize the result: {error}")))
    }
}

