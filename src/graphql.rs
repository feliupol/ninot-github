/// `User.repositories` and `Organization.repositories`: the owner's repositories visible to the
/// caller, filtered by `privacy` and `isFork`, ordered by `orderBy` and paginated with opaque
/// cursors.
fn repositories(env: &Env, parent: &Map, args: &Map) -> Result<Output, Error> {
    let AccountKey { login } = read(parent)?;
    let args: RepositoriesArgs = read(args)?;
    let state = lock(&env.state);
    let mut repos: Vec<&Repo> = state
        .account(&login)
        .map(|account| {
            account
                .repos()
                .filter(|repo| {
                    state
                        .permission(Some(&env.caller), &login, &repo.name)
                        .is_some()
                })
                .collect()
        })
        .unwrap_or_default();
    match args.privacy {
        Some(RepositoryPrivacy::Public) => repos.retain(|repo| !repo.private),
        Some(RepositoryPrivacy::Private) => repos.retain(|repo| repo.private),
        None => {}
    }
    if args.is_fork == Some(true) {
        repos.clear();
    }
    if let Some(order) = args.order_by {
        match order.field {
            RepositoryOrderField::Name => repos.sort_by_key(|repo| repo.name.to_lowercase()),
            RepositoryOrderField::CreatedAt => {
                repos.sort_by(|a, b| a.created_at.cmp(&b.created_at).then(a.id.cmp(&b.id)))
            }
            RepositoryOrderField::UpdatedAt => {
                repos.sort_by(|a, b| a.updated_at.cmp(&b.updated_at).then(a.id.cmp(&b.id)))
            }
            _ => repos.sort_by(|a, b| {
                read::repo_pushed_or_created(a)
                    .cmp(&read::repo_pushed_or_created(b))
                    .then(a.id.cmp(&b.id))
            }),
        }
        if order.direction == types::OrderDirection::Desc {
            repos.reverse();
        }
    }
    let total = repos.len();
    let start = args
        .after
        .and_then(|cursor| STANDARD.decode(cursor).ok())
        .and_then(|bytes| String::from_utf8(bytes).ok())
        .and_then(|text| grammar::cursor.parse(text.as_str()).ok())
        .map_or(0, |index| index + 1);
    let count = args.first.unwrap_or(30).clamp(0, 100) as usize;
    let end = (start + count).min(total);
    let cursor = |index: usize| STANDARD.encode(format!("cursor:{index}"));
    let account = state.account(&login);
    let nodes = repos
        .get(start..end)
        .unwrap_or_default()
        .iter()
        .filter_map(|repo| Some(repository_object(env, account?, repo)))
        .collect();
    Output::of(Connection {
        nodes,
        total_count: total,
        page_info: PageInfo {
            has_next_page: end < total,
            has_previous_page: start > 0,
            end_cursor: (end > start).then(|| cursor(end - 1)),
            start_cursor: (end > start).then(|| cursor(start)),
        },
    })
}

/// The stored repository behind a repository object.
fn stored_repo<'a>(state: &'a State, repository: &Map) -> Result<Option<&'a Repo>, Error> {
    let RepositoryKey { owner, name } = read(repository)?;
    Ok(read::repo(state, &owner.login, &name))
}

/// `Repository.isEmpty`.
fn is_empty(env: &Env, parent: &Map, _: &Map) -> Result<Output, Error> {
    let git_dir = stored_repo(&lock(&env.state), parent)?.and_then(|repo| repo.git_dir.clone());
    Output::of(git_dir.is_none_or(|git_dir| git::is_empty(&git_dir).unwrap_or(true)))
}

/// `Repository.defaultBranchRef`: null until the default branch exists.
fn default_branch_ref(env: &Env, parent: &Map, _: &Map) -> Result<Output, Error> {
    let Some((git_dir, default_branch)) = stored_repo(&lock(&env.state), parent)?
        .and_then(|repo| Some((repo.git_dir.clone()?, repo.default_branch.clone())))
    else {
        return Output::of(None::<Ref>);
    };
    let name = format!("refs/heads/{default_branch}");
    let exists = git::refs(&git_dir, &name)
        .is_ok_and(|refs| refs.into_iter().any(|found| found.name == name));
    Output::of(exists.then_some(Ref {
        typename: "Ref",
        name: default_branch,
        prefix: "refs/heads/",
    }))
}

/// `Repository.viewerPermission`.
fn viewer_permission(env: &Env, parent: &Map, _: &Map) -> Result<Output, Error> {
    let RepositoryKey { owner, name } = read(parent)?;
    let state = lock(&env.state);
    let permission = state.permission(Some(&env.caller), &owner.login, &name);
    Output::of(permission.map(|permission| {
        if permission.admin {
            types::RepositoryPermission::Admin
        } else if permission.push {
            types::RepositoryPermission::Write
        } else {
            types::RepositoryPermission::Read
        }
    }))
}

/// `Repository.autoMergeAllowed`.
fn auto_merge_allowed(env: &Env, parent: &Map, _: &Map) -> Result<Output, Error> {
    let allowed = stored_repo(&lock(&env.state), parent)?
        .ok_or_else(|| Error::new("repository does not exist"))?
        .settings
        .allow_auto_merge;
    Output::of(allowed)
}

/// Global id for a pull request, combining its repository id and number.
fn pull_id(repository_id: u64, number: u64) -> u64 {
    (repository_id << 32) | (number & u32::MAX as u64)
}

/// The result of `Repository.pullRequest`.
#[derive(serde::Serialize)]
#[serde(untagged)]
enum FoundPullRequest {
    /// A pull request with its REST model.
    Full(Box<objects::PullRequest>),
    /// A pull request seeded for GraphQL review state alone.
    Number(Box<objects::PullRequestNumber>),
}

/// `Repository.pullRequest(number)`.
fn pull_request(env: &Env, parent: &Map, args: &Map) -> Result<Output, Error> {
    let RepositoryKey { owner, name } = read(parent)?;
    let NumberArgs { number } = read(args)?;
    let number = u64::try_from(number).unwrap_or_default();
    let state = lock(&env.state);
    let account = state
        .account(&owner.login)
        .ok_or_else(|| Error::new("repository does not exist"))?;
    let repo = account
        .repo(&name)
        .ok_or_else(|| Error::new("repository does not exist"))?;
    let pull = repo
        .pull_requests
        .get(&number)
        .ok_or_else(|| Error::new("pull request does not exist"))?;
    Output::of(match pull_object(env, account, repo, number, pull)? {
        Some(full) => FoundPullRequest::Full(Box::new(full)),
        None => FoundPullRequest::Number(Box::new(objects::PullRequestNumber {
            typename: "PullRequest",
            id: node_id("PullRequest", pull_id(repo.id, number)),
            database_id: pull_id(repo.id, number),
            number,
            repository: repository_object(env, account, repo),
        })),
    })
}

/// Finds the pull request encoded by a Relay global id.
fn pull_location(state: &State, encoded: &str) -> Option<(String, String, u64)> {
    let id = database_id(encoded)?;
    let repository_id = id >> 32;
    let number = id & u32::MAX as u64;
    state.accounts().find_map(|account| {
        account
            .repos()
            .find(|repo| repo.id == repository_id && repo.pull_requests.contains_key(&number))
            .map(|repo| (account.login.clone(), repo.name.clone(), number))
    })
}

/// The input of `Mutation.enablePullRequestAutoMerge` and `disablePullRequestAutoMerge` that
/// is applied.
